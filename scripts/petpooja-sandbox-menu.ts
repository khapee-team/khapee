/**
 * Build the sandbox menu out of Mr. Beans' real menu.
 *
 *   npx tsx scripts/petpooja-sandbox-menu.ts > tests/fixtures/petpooja-sandbox-menu.json
 *
 * Certification needs a menu in the shape Petpooja pushes, and Petpooja cannot
 * push one until the café is live at their end — their Fetch Menu API answers
 * "unable to fetch Object from s3 bucket" because the push is what generates
 * the object it reads. So the shape is theirs and the contents are ours: every
 * dish, price, add-on and variation below is read out of
 * data/mrbeans-saket-oct-2026.json, which is the Saket menu as printed.
 *
 * The one thing that cannot be real is the POS identifiers. itemid,
 * addonitemid and variationid are allocated by Petpooja when a menu is pushed,
 * so until that happens there is nothing to copy; the numbers here are made up
 * and stable (position in the file), which their sandbox accepts because it
 * does not check them. When a real menu does arrive it is kept in
 * petpooja_links.last_menu_json and the certification script prefers it over
 * this file without being told to.
 *
 * Taxes are the 5% a restaurant charges on food, as the two halves it is
 * actually levied in: CGST 2.5 and SGST 2.5.
 */
import fs from 'node:fs'
import path from 'node:path'

const source = path.join(import.meta.dirname, '..', 'data', 'mrbeans-saket-oct-2026.json')
const menu = JSON.parse(fs.readFileSync(source, 'utf8')) as {
  note: string
  addonGroups: Record<string, { name: string; max: number; items: [string, number, string][] }>
  menu: { section: string; items: { name: string; price: number; description?: string; type?: string; addons?: string[]; variations?: [string, number][] }[] }[]
}

/* --- Taxes ------------------------------------------------------------------- */

const taxes = [
  { taxid: '11213', taxname: 'CGST', tax: '2.5', taxtype: '1', tax_ordertype: '1,2,3', active: '1' },
  { taxid: '20375', taxname: 'SGST', tax: '2.5', taxtype: '1', tax_ordertype: '1,2,3', active: '1' },
]
const itemTax = taxes.map((t) => t.taxid).join(',')

/* --- Add-on groups ----------------------------------------------------------- */

// Keyed so an item's "addons": ["egg-extras"] can be turned into a link.
const groupIds = new Map<string, string>()
const addongroups = Object.entries(menu.addonGroups).map(([key, g], gi) => {
  const addongroupid = String(9001 + gi)
  groupIds.set(key, addongroupid)
  return {
    addongroupid,
    addongroup_name: g.name,
    addongroup_rank: String(gi + 1),
    active: '1',
    addongroupitems: g.items.map(([name, price], ai) => ({
      addonitemid: `${addongroupid}${ai + 1}`,
      addonitem_name: name,
      addonitem_price: String(price),
      addonitem_rank: String(ai + 1),
      active: '1',
    })),
  }
})

/* --- Items ------------------------------------------------------------------- */

let n = 0
const items = menu.menu.flatMap((section) =>
  section.items.map((it) => {
    const itemid = String(10001 + n++)
    const links = (it.addons ?? [])
      .filter((key) => groupIds.has(key))
      .map((key) => ({
        addon_group_id: groupIds.get(key)!,
        addon_item_selection_min: '0', // every add-on on this menu is optional
        addon_item_selection_max: String(menu.addonGroups[key].max),
      }))
    const variations = (it.variations ?? []).map(([name, price], vi) => ({
      id: `${itemid}${vi + 1}`,
      variationid: `${itemid}${vi + 1}`,
      name,
      groupname: 'Choice',
      price: String(price),
      active: '1',
      item_packingcharges: '0',
      variationrank: String(vi + 1),
      addon: [],
    }))
    return {
      itemid,
      itemname: it.name,
      itemdescription: it.description ?? '',
      // A dish priced by its variations carries no price of its own, which is
      // how Petpooja sends it; everything else carries the printed price.
      price: variations.length ? '0' : String(it.price),
      active: '1',
      in_stock: '2',
      item_tax: itemTax,
      item_categoryid: String(section.section),
      itemallowvariation: variations.length ? '1' : '0',
      itemallowaddon: links.length ? '1' : '0',
      item_attributeid: it.type === 'veg' ? '1' : it.type === 'egg' ? '24' : '2',
      variation: variations,
      addon: links,
    }
  }),
)

const out = {
  success: '1',
  restaurants: [
    {
      details: {
        // A plain hyphen, not the em dash the app shows: this string is read by
        // a point-of-sale, and the one that cannot be mis-encoded is better.
        restaurantname: 'Mr. Beans - Saket',
        address: 'Saket, Indore',
        city: 'Indore',
        state: 'Madhya Pradesh',
        country: 'India',
      },
    },
  ],
  taxes,
  addongroups,
  items,
  _readme:
    'Generated by scripts/petpooja-sandbox-menu.ts from data/mrbeans-saket-oct-2026.json — ' +
    "Mr. Beans' own dishes, prices, add-ons and variations, in the shape Petpooja pushes a menu in. " +
    'The POS ids (itemid, addonitemid, variationid) are stand-ins: Petpooja allocates those on a real ' +
    'push, and their sandbox does not check them. Regenerate rather than edit by hand.',
}

process.stdout.write(JSON.stringify(out, null, 2) + '\n')
